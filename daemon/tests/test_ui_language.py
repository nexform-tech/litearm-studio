"""首屏语言的来源 —— `ui_language` 的解析规则。

这些用例钉住的是"哪一套变量说了算": 桌面翻译用 gettext 的 `LANGUAGE`, 而 WebKitGTK
的 `navigator.language` 只看 POSIX locale。把两者混起来, 就是"系统是中文、界面是英文"
的那一类报告。
"""
from __future__ import annotations

from pathlib import Path

import pytest

from litearm_studio_daemon.ui_language import desktop_languages, script

#: 一个不存在的路径 —— 让用例明确表示"没有系统级文件可读"。
NO_FILE = Path("/nonexistent/etc/default/locale")


def test_language_list_comes_first() -> None:
    """`LANGUAGE` 是桌面实际用来翻译的那一份, 优先级高于 LANG。"""
    assert desktop_languages(
        {"LANGUAGE": "zh_CN:zh", "LANG": "en_US.UTF-8"}, NO_FILE
    ) == ["zh-CN", "zh", "en-US"]


def test_posix_locale_is_used_when_language_is_absent() -> None:
    assert desktop_languages({"LANG": "zh_CN.UTF-8"}, NO_FILE) == ["zh-CN"]


@pytest.mark.parametrize("value", ["zh_CN.UTF-8", "zh_CN.utf8", "zh_CN"])
def test_locale_names_are_normalized_to_bcp47(value: str) -> None:
    assert desktop_languages({"LANG": value}, NO_FILE) == ["zh-CN"]


@pytest.mark.parametrize("value", ["C", "C.UTF-8", "POSIX", ""])
def test_c_locales_contribute_no_language(value: str) -> None:
    assert desktop_languages({"LANG": value}, NO_FILE) == []


def test_duplicates_are_dropped_but_the_order_is_kept() -> None:
    """同一个 zh 在 `LANGUAGE` 与 `LANG` 里各出现一次, 不能变成两个候选。"""
    assert desktop_languages(
        {"LANGUAGE": "zh_CN:zh", "LANG": "zh_CN.UTF-8"}, NO_FILE
    ) == ["zh-CN", "zh"]


def test_lc_all_outranks_lc_messages_and_lang() -> None:
    assert desktop_languages(
        {"LC_ALL": "zh_CN.UTF-8", "LC_MESSAGES": "en_US.UTF-8", "LANG": "en_US.UTF-8"},
        NO_FILE,
    ) == ["zh-CN", "en-US"]


def test_the_system_locale_file_is_the_last_resort(tmp_path: Path) -> None:
    """裸 SSH / service 的进程里没有 locale 变量时, 用桌面登录会用的那一份。"""
    locale_file = tmp_path / "locale"
    locale_file.write_text(
        '# Generated by update-locale\nLANG="zh_CN.UTF-8"\nLANGUAGE="zh_CN:zh"\n',
        encoding="utf-8",
    )
    assert desktop_languages({}, locale_file) == ["zh-CN", "zh"]


def test_an_environment_value_beats_the_system_locale_file(tmp_path: Path) -> None:
    locale_file = tmp_path / "locale"
    locale_file.write_text('LANG="zh_CN.UTF-8"\n', encoding="utf-8")
    assert desktop_languages({"LANG": "en_US.UTF-8"}, locale_file) == ["en-US"]


def test_an_explicit_c_locale_does_not_read_the_system_locale_file(tmp_path: Path) -> None:
    """服务进程刻意留在 C locale 时, 系统文件里的中文不该把它改回来。"""
    locale_file = tmp_path / "locale"
    locale_file.write_text('LANG="zh_CN.UTF-8"\n', encoding="utf-8")
    assert desktop_languages({"LANG": "C.UTF-8"}, locale_file) == []


def test_a_missing_or_unreadable_file_is_not_an_error() -> None:
    assert desktop_languages({}, NO_FILE) == []


def test_the_script_sets_the_window_list_and_escapes_it() -> None:
    assert script([]) == "window.__LITEARM_UI_LANGUAGES__ = [];\n"
    assert script(["zh-CN", "zh"]) == (
        'window.__LITEARM_UI_LANGUAGES__ = ["zh-CN", "zh"];\n')
